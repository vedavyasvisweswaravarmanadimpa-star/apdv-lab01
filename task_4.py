# Task 4: The math module contains the constants e and pi
import math

# 1. Print pi and e to three decimal places
print("pi = {:.3f}".format(math.pi))
print("e  = {:.3f}".format(math.e))

# 2. Compute pi^e and print to two decimal places
print("pi ** e = {:.2f}".format(math.pi ** math.e))

# 3. Compute e^pi and print to two decimal places
print("e ** pi = {:.2f}".format(math.e ** math.pi))